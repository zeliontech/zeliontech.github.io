// Cuts the pillar-card art from the same on-site scene as the hero, so every
// photograph on the homepage belongs to one family.
//
//   npm i --no-save sharp@0.33.5
//   node scripts/images/build-card-image.mjs path/to/zev-scene-source.png
//
// Source is 1672x941. The device body spans roughly x 380-610 and the logo
// sits at y 290-360; the solar array runs along y 520-700 with the field
// below it. The cards render at most ~430 CSS px wide, so 800 to 900 px
// covers 2x.
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..");
const SRC = process.argv[2] || path.join(REPO, "assets-source", "zev-scene-source.png");
const OUT = path.join(REPO, "public", "zev");
const MODULE = path.join(REPO, "src", "components", "zev", "card-image.js");

const CUTS = [
  {
    // The device card: upper body with the logo centred, rising out of the
    // ink at the top of the card.
    name: "zev-device-card",
    exportName: "CARD_IMAGE",
    region: { left: 100, top: 150, width: 800, height: 400 },
  },
  {
    // The carbon card: the array and the field to the right of the device,
    // dissolving into the white card at the top.
    name: "zev-array-card",
    exportName: "ARRAY_IMAGE",
    region: { left: 760, top: 470, width: 900, height: 450 },
  },
];

async function main() {
  if (!fs.existsSync(SRC)) {
    throw new Error("Source image not found: " + SRC + " (pass the path as the first argument)");
  }
  let module = `// Generated by scripts/images/build-card-image.mjs from the owner-supplied ZEV
// scene. Do not edit by hand; rerun the script.
`;
  for (const cut of CUTS) {
    const base = sharp(SRC).extract(cut.region);
    const avif = await base.clone().avif({ quality: 58, effort: 6 }).toFile(path.join(OUT, `${cut.name}.avif`));
    const webp = await base.clone().webp({ quality: 78, effort: 6 }).toFile(path.join(OUT, `${cut.name}.webp`));
    const jpg = await base.clone().jpeg({ quality: 80, progressive: true, mozjpeg: true }).toFile(path.join(OUT, `${cut.name}.jpg`));
    console.log(cut.name, "avif", avif.size, "webp", webp.size, "jpg", jpg.size, avif.width + "x" + avif.height);
    module += `
export const ${cut.exportName} = {
  width: ${avif.width},
  height: ${avif.height},
  avif: "/zev/${cut.name}.avif",
  webp: "/zev/${cut.name}.webp",
  jpg: "/zev/${cut.name}.jpg",
};
`;
  }
  fs.writeFileSync(MODULE, module);
  console.log("wrote", path.relative(REPO, MODULE));
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
