// Cuts the ZEV pillar-card art from the same on-site scene as the hero.
//
//   npm i --no-save sharp@0.33.5
//   node scripts/images/build-card-image.mjs path/to/zev-scene-source.png
//
// Source is 1672x941. The device body spans roughly x 380-610 and the logo
// sits at y 290-360. An 800x400 window from (100, 150) frames the upper body
// with the logo centred, the tower rising out of the ink at the top of the
// card, the hills and turbines behind and the first row of panels along the
// bottom. The card renders at most ~430 CSS px wide, so 800 px covers 2x.
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..");
const SRC = process.argv[2] || path.join(REPO, "assets-source", "zev-scene-source.png");
const OUT = path.join(REPO, "public", "zev");
const MODULE = path.join(REPO, "src", "components", "zev", "card-image.js");

const REGION = { left: 100, top: 150, width: 800, height: 400 };

async function main() {
  if (!fs.existsSync(SRC)) {
    throw new Error("Source image not found: " + SRC + " (pass the path as the first argument)");
  }
  const base = sharp(SRC).extract(REGION);
  const avif = await base.clone().avif({ quality: 58, effort: 6 }).toFile(path.join(OUT, "zev-device-card.avif"));
  const webp = await base.clone().webp({ quality: 78, effort: 6 }).toFile(path.join(OUT, "zev-device-card.webp"));
  const jpg = await base.clone().jpeg({ quality: 80, progressive: true, mozjpeg: true }).toFile(path.join(OUT, "zev-device-card.jpg"));
  console.log("card avif", avif.size, "webp", webp.size, "jpg", jpg.size, avif.width + "x" + avif.height);

  const module = `// Generated by scripts/images/build-card-image.mjs from the owner-supplied ZEV
// scene. Do not edit by hand; rerun the script.

export const CARD_IMAGE = {
  width: ${avif.width},
  height: ${avif.height},
  avif: "/zev/zev-device-card.avif",
  webp: "/zev/zev-device-card.webp",
  jpg: "/zev/zev-device-card.jpg",
};
`;
  fs.writeFileSync(MODULE, module);
  console.log("wrote", path.relative(REPO, MODULE));
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
