// Builds the responsive homepage hero set from the ZEV on-site scene.
//
//   npm i --no-save sharp@0.33.5
//   node scripts/images/build-hero-image.mjs path/to/zev-scene-source.png
//
// The source is the owner-supplied 1672x941 PNG of the device among solar
// arrays and wind turbines. It is not committed (2 MB, and it is a raw
// render); the default path below is gitignored. Outputs land in public/zev
// and the srcsets plus a 24px blurred placeholder are written to
// src/components/zev/hero-image.js, which the hero imports.
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..");
const SRC = process.argv[2] || path.join(REPO, "assets-source", "zev-scene-source.png");
const OUT = path.join(REPO, "public", "zev");
const MODULE = path.join(REPO, "src", "components", "zev", "hero-image.js");

const WIDTHS = [800, 1200, 1600];

async function main() {
  if (!fs.existsSync(SRC)) {
    throw new Error("Source image not found: " + SRC + " (pass the path as the first argument)");
  }
  const meta = await sharp(SRC).metadata();
  console.log("source", meta.width, meta.height);

  for (const w of WIDTHS) {
    const base = sharp(SRC).resize({ width: w, withoutEnlargement: true });
    const avif = await base.clone().avif({ quality: 58, effort: 6 }).toFile(path.join(OUT, `zev-scene-${w}.avif`));
    const webp = await base.clone().webp({ quality: 78, effort: 6 }).toFile(path.join(OUT, `zev-scene-${w}.webp`));
    const jpg = await base.clone().jpeg({ quality: 80, progressive: true, mozjpeg: true }).toFile(path.join(OUT, `zev-scene-${w}.jpg`));
    console.log(w, "avif", avif.size, "webp", webp.size, "jpg", jpg.size, "h", avif.height);
  }

  // Blurred placeholder: 24px wide, painted behind the picture while it loads.
  const tiny = await sharp(SRC).resize({ width: 24 }).webp({ quality: 40 }).toBuffer();
  const placeholder = "data:image/webp;base64," + tiny.toString("base64");
  console.log("placeholder bytes", tiny.length);

  const srcset = (ext) => WIDTHS.map((w) => `/zev/zev-scene-${w}.${ext} ${w}w`).join(", ");
  const module = `// Generated by scripts/images/build-hero-image.mjs from the owner-supplied ZEV
// scene (${meta.width}x${meta.height} source). Do not edit by hand; rerun the script.

export const HERO_IMAGE = {
  width: ${meta.width},
  height: ${meta.height},
  avif: "${srcset("avif")}",
  webp: "${srcset("webp")}",
  jpg: "${srcset("jpg")}",
  fallback: "/zev/zev-scene-1200.jpg",
  // Desktop: the stage is the right 7/12 of a container capped at 1280px, so
  // 720px is the largest rendered width; below lg the stage is full width.
  // Keep in step with the <link rel="preload"> in index.html.
  sizes: "(min-width: 1024px) 720px, 100vw",
  placeholder: "${placeholder}",
};
`;
  fs.writeFileSync(MODULE, module);
  console.log("wrote", path.relative(REPO, MODULE));
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
